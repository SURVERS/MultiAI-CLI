export type DevPhraseMode = keyof typeof DEV_PHRASES;

export function getRandomDevPhrase(mode: DevPhraseMode, excludePhrase?: string): string {
  const pool = DEV_PHRASES[mode];
  if (!pool || pool.length === 0) return 'думаю...';
  const candidates =
    excludePhrase && pool.length > 1
      ? pool.filter((phrase) => phrase !== excludePhrase)
      : pool;
  const picked = candidates[Math.floor(Math.random() * candidates.length)] ?? pool[0]!;
  return picked;
}
